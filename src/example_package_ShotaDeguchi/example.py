def add_one(number):
    """
    Adds one to the given number.

    Parameters
    ----------
    number : int or float
        The number to which one will be added.

    Returns
    -------
    int or float
        The result of adding one to the input number.
    """
    return number + 1


def multiply(number1, number2):
    """
    Multiplies two numbers.

    Parameters
    ----------
    number1 : int or float
        The first number to multiply.
    number2 : int or float
        The second number to multiply.

    Returns
    -------
    int or float
        The product.
    """
    return number1 * number2
